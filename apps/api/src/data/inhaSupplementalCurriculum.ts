const departmentAliases: Record<string, string> = {
  건축공학전공: "건축학부",
  건축학전공: "건축학부",
};

export function findInhaSupplementalCurriculum(department: string) {
  const normalized = normalizeDepartmentName(department);
  const alias = departmentAliases[department] ?? department;
  return (
    inhaSupplementalCurricula.find(
      (item) => normalizeDepartmentName(item.department) === normalized,
    ) ??
    inhaSupplementalCurricula.find(
      (item) => normalizeDepartmentName(item.department) === normalizeDepartmentName(alias),
    ) ??
    null
  );
}

export function summarizeInhaSupplementalCurriculum(admissionDepartments: string[]) {
  const matchedDepartments = admissionDepartments.filter((department) => {
    const supplemental = findInhaSupplementalCurriculum(department);
    return Boolean(supplemental?.courses.length);
  });

  return {
    publicDepartmentCount: inhaSupplementalCurricula.length,
    publicCourseBackedDepartmentCount: inhaSupplementalCurricula.filter(
      (item) => item.courses.length > 0,
    ).length,
    matchedAdmissionDepartmentCount: matchedDepartments.length,
    archetypeOnlyDepartmentCount: admissionDepartments.length - matchedDepartments.length,
    missingAdmissionDepartments: admissionDepartments.filter(
      (department) => !matchedDepartments.includes(department),
    ),
  };
}

function normalizeDepartmentName(department: string) {
  return department.replace(/\s*\(야\)$/, "").replace(/\s+/g, "").trim();
}
